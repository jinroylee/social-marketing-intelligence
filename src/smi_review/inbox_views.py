"""Escaped completion messages composed by the policy-aware inbox owner."""

import uuid

from .views import brief_summary, e, error_message, hidden, options, profile_summary, value


def index(events, monitoring_notifications=()):
    """List bounded completion events without copying source or task-purpose text."""
    content = '<h1>Completion inbox</h1><p>Latest 100 task completions. Publication availability is checked when reopened.</p>'
    for event in events:
        content += f'<section class="panel"><a href="/inbox/{e(event["event_id"])}">Completion {e(event["created_at"])}</a>'
        content += detail(event, heading=False) + '</section>'
    if not events:
        content += '<p>No completed tasks yet.</p>'
    content += '<h2>Monitoring alerts</h2><p>Latest 100 durable local alert notifications; current source support is checked when reopened.</p>'
    for notification in monitoring_notifications:
        content += f'<section class="panel"><p><a href="{e(notification["href"])}">X volume alert {e(notification["created_at"])}</a></p><p>{e(notification["message"])}</p></section>'
    return content


def detail(event, *, heading=True):
    """Show historical counts separately from current permitted publication links."""
    content = '<h1>Task completion</h1><p><a href="/inbox">Completion inbox</a></p>' if heading else ''
    content += f'<p>{e(event["message"])}</p><p><a href="{e(event["task_href"])}">Task {e(event["task_id"])}</a></p>'
    content += f'<p>Outcome: {e(event["outcome"])} · Completed: {e(event["created_at"])}</p>'
    coverage = event['coverage']
    content += '<p>' + ' · '.join(f'{label}: {e(coverage.get(field, "unknown"))}' for label, field in (
        ('Requested inputs', 'requested_inputs'), ('Collected', 'collected_observations'),
        ('Ingested', 'ingested_observations'), ('Quarantined', 'quarantined_observations'),
    )) + '</p><p>Coverage is limited to requested inputs. Market coverage is unknown.</p>'
    for publication in event['publications']:
        if publication['href']:
            content += f'<p><a href="{e(publication["href"])}">Publication {e(publication["publication_id"])}</a></p>'
        else:
            content += f'<p>Publication {e(publication["publication_id"])}: current support unavailable.</p>'
    discovery = event.get('campaign_discovery')
    if discovery:
        content += f'<p><a href="/campaigns/{e(discovery["campaign_id"])}">Campaign</a> · <a href="/shortlists/{e(discovery["shortlist_id"])}">Original saved shortlist</a></p>'
        if discovery['regeneration_href']:
            content += f'<p>New published support is available. Saved recommendations stay unchanged. <a href="{e(discovery["regeneration_href"])}">Offer to regenerate</a></p>'
        else:
            content += f'<p>Regeneration offer unavailable: {e(discovery["reason"])}. This completion offers no new currently usable evidence.</p>'
    return content


def regeneration(offer, csrf, submitted=None, error=None):
    """Offer explicit assessment without source copies or client-controlled authority."""
    event, campaign = offer['event'], offer['campaign']
    current = campaign['briefs'][-1]
    action = f'/inbox/{event["event_id"]}/regenerate'
    content = '<h1>Regenerate campaign recommendations</h1>' + detail(event, heading=False)
    if error:
        content += error_message(error)
    content += f'<p>Assessment: {"Validated LLM assessment order" if offer["ranked"] else "Deterministic and unranked"}. Uses the current campaign brief and permitted knowledge when submitted. A saved result does not establish improvement or human endorsement.</p>'
    content += f'<p>Current brief: {e(current["id"])} · version {e(current["version"])}. Current shortlist version: {e(campaign["shortlist_version"])}.</p>'
    content += brief_summary(current)
    for interpretation in campaign['interpretations']:
        config = interpretation['configuration']
        content += f'<section class="panel"><h2>Model-generated interpretation</h2><p>{e(interpretation["interpretation_id"])} · requested by {e(interpretation["requested_by"])} · generated by automation</p>'
        content += f'<p>Model: {e(config["model"])} / {e(config["model_version"])} · method: {e(config["method_version"])} · schema: {e(config["schema_version"])} · {e(config["execution"])}</p>'
        content += profile_summary(interpretation['executable_profile']) + '</section>'
    history = ''
    for record in offer['actions']:
        history += f'<section class="panel"><p>Explicit request {e(record["request_id"])} by {e(record["initiator"]["actor_id"])} · {e(record["recorded_at"])}.</p>'
        outcome = record['outcome']
        if outcome:
            history += f'<p>Assessment outcome: {e(outcome["status"])} · {e(outcome.get("reason") or "Saved automatically; confirmation is separate.")}</p>'
            if outcome.get('operation_id'):
                history += f'<p><a href="/costs/{e(outcome["operation_id"])}">Assessment costs</a></p>'
            if outcome.get('shortlist_id'):
                history += f'<a href="/shortlists/{e(outcome["shortlist_id"])}">Saved successor</a>'
        else:
            history += '<p>Request recorded; in flight or interrupted. Completion is not recorded here. Retry the exact request to reopen committed assessment progress.</p>'
            if not record['body']['include_synthetic']:
                history += f'<form method="post" action="{e(action)}">{hidden("csrf", csrf)}{hidden("request_id", record["request_id"])}'
                for name in ('brief_id', 'expected_brief_version', 'expected_shortlist_version', 'interpretation_id'):
                    history += hidden(name, record['body'][name] if record['body'][name] is not None else '')
                history += '<button type="submit">Reopen exact request</button></form>'
        history += '</section>'
    if event['campaign_discovery']['regeneration_href'] or submitted:
        content += '<p>Submitting explicitly creates a successor under current brief and shortlist concurrency checks. If context changed, inspect the current campaign and reopen this page for a new request.</p>'
        content += f'<p><a href="{e(action)}#new-request">Reload current context for a new request</a></p>'
        profiles = [('', 'Human structured profile')] + [(i['interpretation_id'], f'Model interpretation {i["interpretation_id"]}')
            for i in campaign['interpretations'] if i['status'] == 'succeeded' and i['brief_id'] == current['id']]
        chosen = value(submitted, 'interpretation_id', '')
        if chosen and chosen not in {identity for identity, _ in profiles}:
            profiles.append((chosen, 'Submitted saved interpretation (stale or unavailable)'))
        content += f'<form id="new-request" method="post" action="{e(action)}">{hidden("csrf", csrf)}'
        for name, default in (('request_id', str(uuid.uuid4())), ('brief_id', current['id']),
                              ('expected_brief_version', current['version']), ('expected_shortlist_version', campaign['shortlist_version'])):
            content += hidden(name, value(submitted, name, default))
        content += f'<label>Executable profile<select name="interpretation_id">{options(profiles, chosen)}</select></label><button type="submit">Regenerate and save successor</button></form>'
    return content + history
