"""Escaped provisional semantic findings and exact current-policy recent support."""

import json
import uuid
from dataclasses import asdict

from . import recent_views
from .views import e, error_message, hidden, value


def index(records, csrf, operator, threshold, submitted=None, error=None):
    """Expose explicit window selection independently of quantitative measurements."""
    content = '<h1>Semantic X assessments</h1><p>One provisional automated product-quality controversy method. Mixed model positions are not independently verified controversy, sentiment, statistical significance or change over time.</p>'
    if error:
        content += error_message(error)
    if operator and threshold:
        content += '<p>Configured distinct-post thresholds: ' + e(json.dumps(asdict(threshold), sort_keys=True)) + '</p>'
        content += f'<form method="post" action="/monitoring/semantic-assessments">{hidden("csrf", csrf)}{hidden("request_id", value(submitted, "request_id", str(uuid.uuid4())))}'
        content += f'<label>Exact recent window ID<input name="window_id" value="{e(value(submitted, "window_id"))}" required></label><button type="submit">Assess possible quality controversy</button></form>'
    else:
        content += '<p>New assessments require a trusted monitoring operator, explicit controversy thresholds and model configuration. Saved assessments reopen without model access.</p>'
    content += '<h2>Latest 100 assessments</h2>'
    for record in records:
        content += f'<p><a href="/monitoring/semantic-assessments/{e(record["assessment_id"])}">{e(record["recorded_at"])}</a> · status {e(record["status"])} · historical outcome {e(record["outcome"])} · current support {e(record["current_support"])}</p>'
    return content


def detail(record):
    """Render exact source excerpts only with all original model inputs usable."""
    content = '<p><a href="/monitoring/semantic-assessments">← Semantic assessment history</a> · <a href="/inbox">Inbox</a></p><h1>Semantic X assessment</h1>'
    content += '<p>Provisional automated interpretation. Position labels and exact quotations do not verify semantic entailment, sentiment, controversy, language accuracy or marketer usefulness. This is distinct from a quantitative measurement.</p>'
    content += f'<p>Status: {e(record["status"])} · historical outcome: {e(record["outcome"])} · current support: {e(record["current_support"])} · usable finding: {e(record["usable"])} · reason: {e(record["reason"])}</p>'
    content += '<p>Comparison: ' + e(json.dumps(record['comparison'], sort_keys=True)) + '</p>'
    if record['usable']:
        for judgment in record['judgments']:
            content += f'<section class="panel"><p>Provisional position: {e(judgment["position"])} · <a href="/monitoring/observations/{e(judgment["observation_id"])}">Exact source capture {e(judgment["native_id"])}</a></p>'
            if judgment['excerpt'] is not None:
                content += f'<blockquote>{e(judgment["excerpt"])}</blockquote><p>Exact source span [{judgment["start"]}, {judgment["end"]}); source claim remains unverified.</p>'
            content += '</section>'
    else:
        content += '<p>Derived finding unavailable. Interrupted claims are never automatically reissued; unavailable source dependencies cannot be restored by a retry.</p>'
    content += '<p>Limitations: ' + e(', '.join(record['limitations'])) + '</p>'
    content += '<h2>Pinned method and model</h2><pre>' + e(json.dumps({'method': record['method'], 'configuration': record['configuration']}, indent=2)) + '</pre>'
    content += f'<p>Requested by {e(record["recorded_by"])} ({e(record["actor_kind"])}) at {e(record["recorded_at"])}. Generated by {e(record["generated_by"]["actor_id"])} (automation).</p>'
    content += '<p>Full prepared model-input capture IDs: ' + e(', '.join(record['input_observation_ids'])) + '; exact input digest: ' + e(record['input_digest']) + '</p>'
    if record['operation_id']:
        content += f'<p><a href="/costs/{e(record["operation_id"])}">Attributable model cost</a></p><pre>{e(json.dumps(record["usage"], indent=2))}</pre>'
    if record['alert_id']:
        content += f'<p>Retained semantic alert: <a href="/monitoring/semantic-alerts/{e(record["alert_id"])}">{e(record["alert_id"])}</a> · local notification {e(record["notification_id"])}</p>'
    content += '<h2>Original collection window and current support</h2>' + recent_views.window(record['window'])
    return content
